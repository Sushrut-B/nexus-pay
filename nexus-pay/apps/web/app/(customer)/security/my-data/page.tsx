"use client";

import { useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Button, Card, CardContent, CardHeader, CardTitle, Input } from "@nexus/ui";
import { apiFetch } from "@/lib/api/client";
import type { DataExportView, DataDeletionView } from "@nexus/shared-types";
import { SecurityNav } from "@/components/security/security-nav";
import { toast } from "sonner";

export default function MyDataPage() {
  const queryClient = useQueryClient();
  const exports = useQuery({ queryKey: ["security", "exports"], queryFn: () => apiFetch<{ exports: DataExportView[] }>("/api/security/exports") });
  const deletions = useQuery({ queryKey: ["security", "deletions"], queryFn: () => apiFetch<{ requests: DataDeletionView[]; retentionNotice: string }>("/api/security/deletions") });
  const [reason, setReason] = useState("");
  const [confirmation, setConfirmation] = useState("");
  const requestExport = useMutation({
    mutationFn: () => apiFetch("/api/security/exports", { method: "POST", body: JSON.stringify({ format: "JSON", idempotencyKey: `export-${Date.now()}` }) }),
    onSuccess: () => { void queryClient.invalidateQueries({ queryKey: ["security", "exports"] }); toast.success("Export requested"); },
  });
  const requestDeletion = useMutation({
    mutationFn: () => apiFetch("/api/security/deletions", { method: "POST", body: JSON.stringify({ reason, confirmation, idempotencyKey: `delete-${Date.now()}` }) }),
    onSuccess: () => { void queryClient.invalidateQueries({ queryKey: ["security", "deletions"] }); setReason(""); setConfirmation(""); toast.success("Deletion request recorded"); },
  });
  const [link, setLink] = useState<string | null>(null);
  return (
    <div className="space-y-6">
      <div><p className="text-xs font-semibold uppercase tracking-[0.16em] text-primary">Security Centre</p><h1 className="mt-2 font-display text-3xl font-semibold text-navy">My data</h1></div>
      <SecurityNav />
      <p className="text-xs text-muted-foreground">Exports are generated by a durable job and delivered through expiring signed links. Deletion requests are reviewable; no financial or ledger record is erased.</p>
      <Card><CardHeader><CardTitle className="text-base">Data exports</CardTitle></CardHeader><CardContent>
        <Button disabled={requestExport.isPending} onClick={() => requestExport.mutate()}>Request JSON export</Button>
        <div className="mt-3">
          {(exports.data?.exports ?? []).length === 0 ? <p className="text-xs text-muted-foreground">No exports yet.</p> : exports.data?.exports.map((item) => (
            <div key={item.id} className="flex flex-wrap justify-between gap-2 border-b border-border/70 py-2 text-xs">
              <span>{item.status} Â· {new Date(item.createdAt).toLocaleString("en-IN")}</span>
              <Button size="sm" variant="outline" disabled={item.status !== "READY"} onClick={async () => {
                const result = await apiFetch<{ url: string }>(`/api/security/exports/${item.id}/link`, { method: "POST", body: "{}" });
                setLink(result.url);
              }}>Get download link</Button>
            </div>
          ))}
        </div>
        {link ? <p className="mt-3 break-all text-xs text-primary"><a href={link}>Open signed export link (5 minutes)</a></p> : null}
      </CardContent></Card>
      <Card><CardHeader><CardTitle className="text-base">Deletion request</CardTitle></CardHeader><CardContent className="grid gap-3">
        <p className="text-xs text-muted-foreground">{deletions.data?.retentionNotice ?? "Loading retention informationâ€¦"}</p>
        <Input placeholder="Reason" value={reason} onChange={(e) => setReason(e.target.value)} />
        <Input placeholder='Type DELETE_MY_ACCOUNT_DATA' value={confirmation} onChange={(e) => setConfirmation(e.target.value)} />
        <Button disabled={requestDeletion.isPending || confirmation !== "DELETE_MY_ACCOUNT_DATA" || reason.length < 5} onClick={() => requestDeletion.mutate()}>Submit deletion request</Button>
        {(deletions.data?.requests ?? []).map((item) => <p key={item.id} className="text-xs">{item.status} Â· {new Date(item.createdAt).toLocaleString("en-IN")}</p>)}
      </CardContent></Card>
    </div>
  );
}
